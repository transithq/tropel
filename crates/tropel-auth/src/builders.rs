        // must still place it correctly for anything that does.
        let mut p = hawk(None);
        p.method = "POST";
        let normalized = hawk_normalized_string(&p, "Yi9LfIIFRtBEPt74PVmbTF/xVAwPn7ub15ePICfgnuY=");
