//! Pure, data-in/data-out auth header builders.
//!
//! # Why this module exists
//!
//! [`crate::signers`] implements every scheme, and every one of them is behind
//! the `reqwest` feature — because those signers mutate a `reqwest::Request`.
//! `reqwest` cannot compile to `wasm32-unknown-unknown`, so `tropel-core-wasm`
//! turns the feature off, and a browser embedder therefore cannot reach ANY of
//! the signers. KnockPort's digest/hawk/SigV4/OAuth1 configs are creatable and
//! importable today, and every send using them REFUSES.
//!
//! The signing itself was never reqwest-coupled — only the plumbing was. The
//! digest builder read exactly two things off the request (`method` and the
//! request-target), and computed everything else from the challenge. So the
//! fix is to move the computation here, ungated, and leave `signers.rs` as a
//! thin adapter that reads those fields off `reqwest::Request` and calls in.
//!
//! # What this module must never become
//!
//! A second implementation. `signers.rs` calls these functions; it does not
//! keep a parallel copy. That is the whole point — a signing byte-difference
//! is a 403 that takes a day to find, which is why D4 puts signing in Rust in
//! the first place. Two Rust copies would be the same mistake one layer down.
//!
//! The `native_vs_wasm` differential harness already covers OAuth1-HMAC, SigV4
//! and Hawk end to end. Anything moved here inherits that coverage precisely
//! because the signers keep calling it.

use base64::Engine as _;
use hmac::digest::KeyInit;
use hmac::{Hmac, Mac};
use md5::Digest as _;
use percent_encoding::{utf8_percent_encode, AsciiSet, NON_ALPHANUMERIC};
use sha1::Sha1;
use sha2::{Sha256, Sha512, Sha512_256};

// ── Hashes ──────────────────────────────────────────────────────────────────
// Moved here from `signers.rs` rather than duplicated: they are shared by the
// digest builders below and by SigV4's canonical-request hashing, and two
// copies of a hash helper is exactly the drift this module exists to prevent.

/// Hex SHA-256.
pub fn hex_sha256(bytes: &[u8]) -> String {
    hex::encode(Sha256::digest(bytes))
}

/// Hex SHA-512/256.
///
/// A SEPARATE hash with a different IV — **not** the first 256 bits of
/// SHA-512. Truncating SHA-512 produces wrong HA1 values (RFC 7616 §3.9.2);
/// that was a real bug here once.
pub fn hex_sha512_256(bytes: &[u8]) -> String {
    hex::encode(Sha512_256::digest(bytes))
}

/// Hex MD5. Weak, and mandatory: RFC 7616 defaults to it when a server omits
/// `algorithm`, and plenty of servers still do.
pub fn hex_md5(bytes: &[u8]) -> String {
    hex::encode(md5::Md5::digest(bytes))
}

/// Hash with the digest algorithm named by a challenge.
///
/// The `-sess` variants change only how HA1 is DERIVED (nonce and cnonce are
/// folded in); the hash function itself stays the base algorithm, so they map
/// to the same arm here.
pub fn digest_with(input: &str, algorithm: &str) -> String {
    match algorithm {
        "SHA-256" | "SHA-256-SESS" => hex_sha256(input.as_bytes()),
        "SHA-512-256" | "SHA-512-256-SESS" => hex_sha512_256(input.as_bytes()),
        _ => hex_md5(input.as_bytes()),
    }
}

// ── HTTP Digest (RFC 7616) ──────────────────────────────────────────────────

/// One header to attach.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HeaderOut {
    pub name: String,
    pub value: String,
}

/// Everything needed to answer a digest challenge.
///
/// Digest is two-phase and the CALLER drives the 401 → retry, so only the
/// challenge-response half is built here. `nc` is the caller's per-host
/// counter; `cnonce` is generated by the caller (CSPRNG in production, a fixed
/// value in tests so vectors are pinnable).
#[derive(Debug, Clone)]
pub struct DigestBuildParams<'a> {
    pub username: &'a str,
    pub password: &'a str,
    /// Uppercase HTTP method.
    pub method: &'a str,
    /// The request-target: path + query. NOT the full URL — RFC 7616's `uri`
    /// is the origin-form target, and signing the absolute URL is a classic
    /// source of 401 loops against strict servers.
    pub uri: &'a str,
    pub realm: &'a str,
    pub nonce: &'a str,
    pub nc: u64,
    pub cnonce: &'a str,
    /// `qop` from the challenge, if it offered one.
    pub qop: Option<&'a str>,
    /// `algorithm` from the challenge. `None` means the server omitted it, in
    /// which case RFC 7616 says MD5 — and the field is NOT echoed back, since
    /// some strict servers reject an explicit `algorithm=MD5`.
    pub algorithm: Option<&'a str>,
    pub opaque: Option<&'a str>,
}

/// Compute the digest `response` value (HA1/HA2 → response).
pub fn digest_response_value(p: &DigestBuildParams<'_>, algorithm: &str) -> String {
    let base = base_algorithm(algorithm);
    let ha1_plain = digest_with(&format!("{}:{}:{}", p.username, p.realm, p.password), base);
    // RFC 7616 §3.4.4: `-sess` folds the nonce and cnonce into HA1.
    let ha1 = if algorithm.to_ascii_uppercase().ends_with("-SESS") {
        digest_with(&format!("{}:{}:{}", ha1_plain, p.nonce, p.cnonce), base)
    } else {
        ha1_plain
    };
    let ha2 = digest_with(&format!("{}:{}", p.method, p.uri), base);
    match p.qop {
        Some(qop) => digest_with(
            &format!(
                "{}:{}:{:08x}:{}:{}:{}",
                ha1, p.nonce, p.nc, p.cnonce, qop, ha2
            ),
            base,
        ),
        None => digest_with(&format!("{}:{}:{}", ha1, p.nonce, ha2), base),
    }
}

/// The base hash for an algorithm name, with `-sess` stripped.
fn base_algorithm(algorithm: &str) -> &'static str {
    let upper = algorithm.to_ascii_uppercase();
    if upper.starts_with("SHA-512-256") {
        "SHA-512-256"
    } else if upper.starts_with("SHA-256") {
        "SHA-256"
    } else {
        "MD5"
    }
}

/// Does this challenge's `qop` offer `auth`?
///
/// `qop` is a comma-separated LIST (`qop="auth,auth-int"`). Only `auth` is
/// supported; `auth-int` needs the entity body folded into HA2, which the
/// caller does not supply. A challenge offering only `auth-int` therefore
/// falls back to the older no-qop form rather than claiming a qop it did not
/// compute — sending `qop=auth` with an `auth-int` response is an
/// authentication failure that looks like a password problem.
fn qop_offers_auth(qop: Option<&str>) -> bool {
    qop.is_some_and(|q| q.split(',').any(|part| part.trim() == "auth"))
}

/// RFC 7616 §3.4.1 field quoting.
///
/// `qop`, `nc` and `algorithm` are `token` productions and MUST NOT be quoted
/// — strict servers reject `qop="auth"`. Everything else is a `quoted-string`
/// and MUST be.
///
/// The escaping is a SECURITY fix, not cosmetic: a username containing `"`, or
/// one ending in `\`, otherwise breaks out of the quoted string and injects
/// directives — reachable from a CSV data file driving a run. Stripping the
/// quotes instead (the older behaviour) silently corrupted the credential:
/// `ab"c` was signed as `abc`.
fn digest_field(key: &str, value: &str) -> String {
    match key {
        "qop" | "nc" | "algorithm" => format!("{key}={value}"),
        _ => format!(
            "{key}=\"{}\"",
            value.replace('\\', "\\\\").replace('"', "\\\"")
        ),
    }
}

/// Build the `Authorization: Digest …` header for a challenge.
///
/// Covers MD5, SHA-256 and SHA-512-256, each with and without `-sess`. Bruno
/// is MD5-only, so this breadth is the differentiator — which is also why it
/// is worth exporting rather than reimplementing.
///
/// The three cases the shape has to get right, all of them interop failures
/// when wrong:
///   1. `qop` offering `auth` — response uses the nc/cnonce form and the
///      header carries `qop`, `nc` and `cnonce`.
///   2. `qop` present but WITHOUT `auth` — fall back to the no-qop response
///      form and do NOT emit `qop`/`nc`.
///   3. no usable `qop` but a `-sess` algorithm — RFC 7616 §3.4.4 still
///      requires a cnonce (it is folded into HA1), so it is emitted even
///      though `nc` is not.
///
/// Field ORDER matches `signers.rs`'s long-standing output byte for byte, so
/// that delegating to this function is not observable on the wire.
pub fn digest_build_authorization(p: &DigestBuildParams<'_>) -> HeaderOut {
    let algorithm = p
        .algorithm
        .map(|a| a.to_ascii_uppercase())
        .unwrap_or_else(|| "MD5".to_string());
    let is_sess = algorithm.ends_with("-SESS");
    let use_qop = qop_offers_auth(p.qop);

    // The response is computed against the qop the header will actually
    // CLAIM, never against the challenge's raw list.
    let effective = DigestBuildParams {
        qop: if use_qop { Some("auth") } else { None },
        ..p.clone()
    };
    let response = digest_response_value(&effective, &algorithm);

    let mut fields: Vec<(&str, String)> = vec![
        ("username", p.username.to_string()),
        ("realm", p.realm.to_string()),
        ("nonce", p.nonce.to_string()),
        ("uri", p.uri.to_string()),
    ];
    if use_qop {
        fields.push(("qop", "auth".to_string()));
        fields.push(("nc", format!("{:08x}", p.nc)));
        fields.push(("cnonce", p.cnonce.to_string()));
    } else if is_sess {
        // Case 3: no nc, but the cnonce is load-bearing for HA1.
        fields.push(("cnonce", p.cnonce.to_string()));
    }
    fields.push(("response", response));
    // Only echo `algorithm` when the server named one (see DigestBuildParams).
    if p.algorithm.is_some() {
        fields.push(("algorithm", algorithm));
    }
    if let Some(opaque) = p.opaque {
        fields.push(("opaque", opaque.to_string()));
    }

    HeaderOut {
        name: "Authorization".to_string(),
        value: format!(
            "Digest {}",
            fields
                .iter()
                .map(|(k, v)| digest_field(k, v))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

// ── Hawk (hawk.1.header) ────────────────────────────────────────────────────

/// Everything needed to build a Hawk `Authorization` header.
///
/// `ts` and `nonce` are caller-supplied so a vector can be pinned; the signer
/// passes the host clock and a CSPRNG nonce.
#[derive(Debug, Clone)]
pub struct HawkBuildParams<'a> {
    /// HTTP method — uppercased internally.
    pub method: &'a str,
    /// Request-target: path + query.
    pub resource: &'a str,
    /// Host WITHOUT brackets for IPv6; the caller brackets if it must.
    pub host: &'a str,
    pub port: u16,
    pub id: &'a str,
    pub key: &'a str,
    /// `"sha256"` (default) or `"sha1"`.
    pub algorithm: Option<&'a str>,
    /// Unix seconds, as a string.
    pub ts: &'a str,
    pub nonce: &'a str,
    /// Application-specific data folded into the MAC. Empty when unused.
    pub ext: &'a str,
}

/// The Hawk normalized request string.
///
/// Field ORDER is the whole contract: scheme, ts, nonce, method, resource,
/// host, port, hash, ext — each followed by a newline. `ts` and `nonce` come
/// FIRST, immediately after the scheme line. An earlier implementation put
/// method/resource/host/port first and produced a MAC every Hawk server
/// rejects, which is why the order is spelled out rather than inferred.
pub fn hawk_normalized_string(p: &HawkBuildParams<'_>, hash: &str) -> String {
    let method = p.method.to_uppercase();
    let host = p.host.to_lowercase();
    format!(
        "hawk.1.header\n{}\n{}\n{method}\n{}\n{host}\n{}\n{hash}\n{}\n",
        p.ts, p.nonce, p.resource, p.port, p.ext
    )
}

/// Hawk request MAC = base64(HMAC(algorithm, key, normalized)).
///
/// Defaults to SHA-256; `"sha1"` selects the legacy variant. Anything else is
/// treated as SHA-256 rather than refused, matching the signer — a Hawk server
/// that wanted SHA-1 will reject the MAC, which is a loud failure at the wire.
pub fn hawk_mac(normalized: &str, key: &str, algorithm: Option<&str>) -> String {
    use base64::Engine as _;
    use hmac::digest::KeyInit as _;
    use hmac::{Hmac, Mac as _};
    use sha1::Sha1;
    let sha1 = algorithm.is_some_and(|a| a.eq_ignore_ascii_case("sha1"));
    if sha1 {
        let mut mac =
            Hmac::<Sha1>::new_from_slice(key.as_bytes()).expect("HMAC-SHA1 accepts any key length");
        mac.update(normalized.as_bytes());
        base64::engine::general_purpose::STANDARD.encode(mac.finalize().into_bytes())
    } else {
        let mut mac = Hmac::<Sha256>::new_from_slice(key.as_bytes())
            .expect("HMAC-SHA256 accepts any key length");
        mac.update(normalized.as_bytes());
        base64::engine::general_purpose::STANDARD.encode(mac.finalize().into_bytes())
    }
}

/// Build the `Authorization: Hawk …` header.
///
/// Payload validation (`hash`) is deliberately not implemented — the signer
/// has never sent one, and emitting an empty `hash=""` would be worse than
/// omitting it. The normalized string still carries the empty hash field,
/// because the spec's field COUNT is fixed.
pub fn hawk_build_header(p: &HawkBuildParams<'_>) -> HeaderOut {
    let normalized = hawk_normalized_string(p, "");
    let mac = hawk_mac(&normalized, p.key, p.algorithm);
    HeaderOut {
        name: "Authorization".to_string(),
        value: format!(
            "Hawk id=\"{}\", ts=\"{}\", nonce=\"{}\", mac=\"{}\"",
            p.id, p.ts, p.nonce, mac
        ),
    }
}

// ── AWS Signature Version 4 ─────────────────────────────────────────────────

// ── SigV4 service rules ─────────────────────────────────────────────────────
// TR-428: these were left in `signers.rs` by TR-426, which made them
// unreachable from `tropel-core-wasm` (`default-features = false` turns the
// `reqwest` feature, and therefore the whole `signers` module, off). A browser
// caller could reach `aws_sigv4_build_headers` but could NOT compute two of
// the inputs it requires — `canonical_uri` and the signing service — so the
// only way to call it from the web tier would have been to re-derive both in
// TypeScript. That is invariant #3, and `default_service`'s comment below
// records exactly what re-deriving it wrongly costs: a 403 on every S3
// request. They live here now.

const VIRTUAL_HOSTED_SERVICE_LABELS: &[&str] = &[
    "s3",
    "s3-control",
    "s3-object-lambda",
    "s3-outposts",
    "s3express",
    "execute-api",
    "es",
    "aoss",
    "cloudsearch",
];

pub fn default_service(host: &str) -> String {
    // Virtual-hosted AWS endpoints put the tenant BEFORE the service label
    // (examplebucket.s3.amazonaws.com, {api-id}.execute-api.{region}.
    // amazonaws.com, {domain}.{region}.es.amazonaws.com), so the first DNS
    // label is NOT the signing service (backlog line 60: the old code derived
    // `examplebucket` / `abc` / `search-x`, breaking the scope, the signing
    // key, and is_s3_family → double-encoded S3 path → 403 on everything).
    // For *.amazonaws.com hosts, scan labels RIGHT-TO-LEFT for a known
    // virtual-hosted service: the service label sits closest to the
    // amazonaws suffix, so this is also collision-robust when a tenant
    // happens to BE a service name (es.s3.amazonaws.com → s3, not es). The
    // S3 website/fips endpoints (bucket.s3-website-{region}…,
    // s3-fips…amazonaws.com) still sign as s3. Everything else keeps the
    // first-label rule (s3.us-west-2.amazonaws.com → s3; non-AWS hosts keep
    // their first label).
    let is_aws = host.ends_with(".amazonaws.com")
        || host.ends_with(".amazonaws.com.cn")
        || host == "amazonaws.com";
    if is_aws {
        for label in host.split('.').rev() {
            if label == "amazonaws" || label == "com" || label == "cn" {
                continue;
            }
            if VIRTUAL_HOSTED_SERVICE_LABELS.contains(&label) {
                return label.to_string();
            }
            if label.starts_with("s3-website-") || label == "s3-fips" {
                return "s3".to_string();
            }
        }
    }
    host.split('.').next().unwrap_or(host).to_string()
}

/// Map a service name to its SigV4 signing name. Most services sign with
/// their own name, but AWS S3 Control uses `s3` as the signing name despite
/// the endpoint prefix being `s3-control` (backlog line 240).
pub fn signing_name(service: &str) -> &str {
    match service {
        "s3-control" | "s3control" => "s3",
        other => other,
    }
}

/// Canonical URI for SigV4.
///
/// AWS requires DOUBLE URI-encoding of the absolute path for every service
/// EXCEPT the S3 family (s3, s3control, s3-object-lambda, s3-outposts,
/// s3express), which sign the single-encoded path exactly as sent. The `url`
/// crate already single-encodes `Url::path()` with the RFC 3986 unreserved
/// rules, so re-encoding each segment yields the required second encoding
/// for non-S3 services (`%` is not unreserved → `%25`). Empty segments
/// (leading/trailing slash, `//`) are preserved; an empty path becomes `/`.
pub fn sigv4_canonical_uri(path: &str, service: &str) -> String {
    if is_s3_family(service) {
        return if path.is_empty() {
            "/".to_string()
        } else {
            path.to_string()
        };
    }
    if path.is_empty() {
        return "/".to_string();
    }
    // Backlog line 240: normalize consecutive slashes — AWS's official
    // test suite expects //prod/users → /prod/users. Without this, the
    // classic base-URL-ends-in-/ join produces a double-slash that fails
    // signature verification with a 403.
    // TR-603: single replace("//","/") only handles pairs; use a loop
    // for runs of 3+ consecutive slashes.
    let mut normalized = path.to_string();
    while normalized.contains("//") {
        normalized = normalized.replace("//", "/");
    }
    let encoded: Vec<String> = normalized
        .split('/')
        .map(percent_encode_unreserved)
        .collect();
    encoded.join("/")
}

/// True for the S3 family of services, which sign the single-encoded path.
///
/// Matches both spellings of S3 Control's signing name ("s3-control" is what
/// `default_service` derives from `s3-control.<region>.amazonaws.com`; some
/// tools emit the un-hyphenated "s3control").
pub fn is_s3_family(service: &str) -> bool {
    matches!(
        service,
        "s3" | "s3control" | "s3-control" | "s3-object-lambda" | "s3-outposts" | "s3express"
    )
}

/// Duplicates are allowed and are what the multi-value comma-join operates on.
#[derive(Debug, Clone)]
/// Everything needed to build the SigV4 headers.
///
/// `headers` is the request's headers in INSERTION order, names as sent.
pub struct AwsSigV4BuildParams<'a> {
    /// Uppercase HTTP method.
    pub method: &'a str,
    /// Path, un-encoded (the canonicalizer encodes it).
    pub path: &'a str,
    /// Raw query string WITHOUT the leading `?`. Empty when there is none.
    pub query: &'a str,
    /// Canonical host — `host[:port]`, port omitted when default for scheme.
    pub host: &'a str,
    pub headers: &'a [(String, String)],
    /// `None` signs UNSIGNED-PAYLOAD.
    pub body: Option<&'a [u8]>,
    pub access_key: &'a str,
    pub secret_key: &'a str,
    pub session_token: Option<&'a str>,
    pub region: &'a str,
    /// The service label used for BOTH the canonical URI rule and the scope.
    pub service: &'a str,
    /// `YYYYMMDDTHHMMSSZ`.
    pub amz_date: &'a str,
    /// `YYYYMMDD` — the scope's date component.
    pub date_stamp: &'a str,
}

/// AWS "Trimall": collapse runs of spaces to one and trim the ends.
pub fn trim_all(value: &str) -> String {
    value.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Canonical query string: pairs sorted by RAW bytes, joined `k=v` with `&`.
///
/// Takes the raw query rather than a parsed URL deliberately — re-encoding a
/// value that is already percent-encoded double-encodes it, and AWS signs the
/// bytes that are on the wire.
pub fn sigv4_canonical_query(query: &str) -> String {
    let mut pairs: Vec<(&str, &str)> = query
        .split('&')
        .filter(|p| !p.is_empty())
        .map(|p| match p.split_once('=') {
            Some((k, v)) => (k, v),
            None => (p, ""),
        })
        .collect();
    pairs.sort();
    pairs
        .iter()
        .map(|(k, v)| format!("{k}={v}"))
        .collect::<Vec<_>>()
        .join("&")
}

/// Canonical headers, sorted by lowercased name.
///
/// Multi-value headers are joined with a BARE COMMA and no space, each value
/// Trimall'd. `", "` produces a different canonical hash and therefore a 403
/// `SignatureDoesNotMatch` on any duplicated header — that was a real bug, so
/// the join is spelled out rather than reached for.
///
/// `authorization` is excluded (it is what we are building). Non-UTF-8 values
/// cannot appear in a canonical request and are skipped rather than panicking.
pub fn sigv4_canonical_headers(
    host: &str,
    headers: &[(String, String)],
    payload_hash: &str,
    amz_date: &str,
    session_token: Option<&str>,
) -> Vec<(String, String)> {
    use std::collections::BTreeMap;
    // BTreeMap gives sorted keys for free.
    let mut grouped: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (name, value) in headers {
        let key = name.to_ascii_lowercase();
        if key == "authorization" {
            continue;
        }
        grouped.entry(key).or_default().push(trim_all(value));
    }
    let mut out: BTreeMap<String, String> = grouped
        .into_iter()
        .filter(|(_, v)| !v.is_empty())
        .map(|(k, v)| (k, v.join(",")))
        .collect();

    out.insert("host".to_string(), host.to_string());
    out.insert("x-amz-content-sha256".to_string(), payload_hash.to_string());
    out.insert("x-amz-date".to_string(), amz_date.to_string());
    if let Some(token) = session_token {
        out.insert("x-amz-security-token".to_string(), token.to_string());
    }
    out.into_iter().collect()
}

fn hmac_sha256_bytes(key: &[u8], data: &[u8]) -> Vec<u8> {
    use hmac::digest::KeyInit as _;
    use hmac::{Hmac, Mac as _};
    let mut mac = Hmac::<Sha256>::new_from_slice(key).expect("HMAC-SHA256 accepts any key length");
    mac.update(data);
    mac.finalize().into_bytes().to_vec()
}

/// Hex HMAC-SHA256.
pub fn hex_hmac_sha256(key: &[u8], data: &[u8]) -> String {
    hex::encode(hmac_sha256_bytes(key, data))
}

/// The SigV4 derived signing key: HMAC chain over date → region → service.
///
/// Uncached here on purpose. `signers.rs` keeps its process-wide cache around
/// this call (the key changes only at UTC midnight, so caching saves four
/// chained HMACs per request); a browser embedder signs one request at a time
/// and does not need it. Caching inside would put a global mutex in the wasm
/// tier for no gain.
pub fn derive_signing_key(secret: &str, date: &str, region: &str, service: &str) -> Vec<u8> {
    let k_date = hmac_sha256_bytes(format!("AWS4{secret}").as_bytes(), date.as_bytes());
    let k_region = hmac_sha256_bytes(&k_date, region.as_bytes());
    let k_service = hmac_sha256_bytes(&k_region, service.as_bytes());
    hmac_sha256_bytes(&k_service, b"aws4_request")
}

/// Everything SigV4 attaches: the `Authorization` header plus the `x-amz-*`
/// headers that are part of the signature and must therefore also be sent.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SigV4Out {
    pub headers: Vec<HeaderOut>,
    /// Exposed for tests and for anyone diffing a 403.
    pub canonical_request: String,
    pub string_to_sign: String,
}

/// Build the SigV4 headers.
///
/// `canonical_uri` is supplied by the caller because the encoding rule is
/// service-dependent — S3 signs the path single-encoded, every other service
/// double-encodes it — and that rule lives with the service derivation in
/// `signers.rs`.
pub fn aws_sigv4_build_headers(
    p: &AwsSigV4BuildParams<'_>,
    canonical_uri: &str,
    signing_service: &str,
    signing_key: &[u8],
) -> SigV4Out {
    let payload_hash = match p.body {
        Some(bytes) => hex_sha256(bytes),
        None => "UNSIGNED-PAYLOAD".to_string(),
    };
    let canonical_query = sigv4_canonical_query(p.query);
    let headers = sigv4_canonical_headers(
        p.host,
        p.headers,
        &payload_hash,
        p.amz_date,
        p.session_token,
    );
    let signed_headers = headers
        .iter()
        .map(|(k, _)| k.as_str())
        .collect::<Vec<_>>()
        .join(";");
    let canonical_headers = headers
        .iter()
        .map(|(k, v)| format!("{k}:{v}\n"))
        .collect::<Vec<_>>()
        .concat();

    let canonical_request = format!(
        "{}\n{canonical_uri}\n{canonical_query}\n{canonical_headers}\n{signed_headers}\n{payload_hash}",
        p.method.to_uppercase()
    );
    let scope = format!(
        "{}/{}/{signing_service}/aws4_request",
        p.date_stamp, p.region
    );
    let string_to_sign = format!(
        "AWS4-HMAC-SHA256\n{}\n{scope}\n{}",
        p.amz_date,
        hex_sha256(canonical_request.as_bytes())
    );
    let signature = hex_hmac_sha256(signing_key, string_to_sign.as_bytes());

    let mut out = vec![HeaderOut {
        name: "Authorization".to_string(),
        value: format!(
            "AWS4-HMAC-SHA256 Credential={}/{scope}, SignedHeaders={signed_headers}, Signature={signature}",
            p.access_key
        ),
    }];
    // These are IN the signature, so they must reach the wire too.
    out.push(HeaderOut {
        name: "x-amz-date".to_string(),
        value: p.amz_date.to_string(),
    });
    out.push(HeaderOut {
        name: "x-amz-content-sha256".to_string(),
        value: payload_hash,
    });
    if let Some(token) = p.session_token {
        out.push(HeaderOut {
            name: "x-amz-security-token".to_string(),
            value: token.to_string(),
        });
    }
    SigV4Out {
        headers: out,
        canonical_request,
        string_to_sign,
    }
}

// ─────────────────────────── OAuth1 (RFC 5849) ───────────────────────────

/// RFC 3986 unreserved characters: `A-Z a-z 0-9 - . _ ~` stay unencoded.
///
/// RFC 5849 §3.6 mandates exactly this set for every OAuth1 encoding — the
/// base string, the signing key and the header parameters. `signers.rs` had
/// its own identical copy; a single definition is the point of this module,
/// because a percent-encoding set that drifts by one character produces a
/// signature the server rejects with no useful diagnostic.
const RFC3986_UNRESERVED: AsciiSet = NON_ALPHANUMERIC
    .remove(b'-')
    .remove(b'.')
    .remove(b'_')
    .remove(b'~');

/// The signature methods [`oauth1_build_header`] implements.
///
/// Exported so the caller's "unsupported method" guard and the builder's own
/// dispatch read from ONE list. When they were separate, adding a method to
/// one and not the other was a silent downgrade — the TR-004/TR-409 failure
/// shape, where an unsupported method quietly signs as HMAC-SHA1.
pub const OAUTH1_SIGNATURE_METHODS: [&str; 3] = ["HMAC-SHA1", "HMAC-SHA256", "HMAC-SHA512"];

/// Whether `method` (case-insensitive) is one of [`OAUTH1_SIGNATURE_METHODS`].
pub fn oauth1_is_supported_signature_method(method: &str) -> bool {
    OAUTH1_SIGNATURE_METHODS
        .iter()
        .any(|m| m.eq_ignore_ascii_case(method))
}

/// RFC 3986 §2.3 percent-encoding: everything except `A-Z a-z 0-9 - . _ ~`.
///
/// Shared, not per-scheme: RFC 5849 §3.6 (OAuth1) and SigV4's canonical URI
/// both specify exactly this set. Two copies of a percent-encoding set is how
/// two signers start disagreeing by one character, which is a 403 with no
/// useful diagnostic.
pub fn percent_encode_unreserved(value: &str) -> String {
    utf8_percent_encode(value, &RFC3986_UNRESERVED).to_string()
}

/// RFC 5849 §3.4.1.1 signature base string.
///
/// `HTTPMethod & "&" & baseURI & "&" & normalizedParams` where the separators
/// are literal `&` characters (ASCII 38), NOT newlines. Each component is
/// percent-encoded per §3.6; params are sorted by encoded name, then encoded
/// value (§3.4.1.3.2), which is why the sort happens AFTER encoding.
pub fn oauth1_base_string(method: &str, base_uri: &str, params: &[(String, String)]) -> String {
    let mut encoded: Vec<(String, String)> = params
        .iter()
        .map(|(k, v)| (percent_encode_unreserved(k), percent_encode_unreserved(v)))
        .collect();
    encoded.sort();
    let param_string = encoded
        .iter()
        .map(|(k, v)| format!("{k}={v}"))
        .collect::<Vec<_>>()
        .join("&");
    format!(
        "{}&{}&{}",
        method.to_uppercase(),
        percent_encode_unreserved(base_uri),
        percent_encode_unreserved(&param_string)
    )
}

/// RFC 5849 §3.4.2 HMAC signature over the base string, base64-encoded.
///
/// Signing key = `percent_encode_unreserved(consumer_secret) & percent_encode_unreserved(token_secret)` — the `&` is
/// present even when the token secret is empty (two-legged OAuth), which is
/// why the caller passes `""` rather than omitting it.
///
/// Returns `None` for a method outside [`OAUTH1_SIGNATURE_METHODS`] rather
/// than falling back to HMAC-SHA1: a silent downgrade is the exact failure
/// TR-409 exists to prevent.
pub fn oauth1_signature(
    base_string: &str,
    consumer_secret: &str,
    token_secret: &str,
    signature_method: &str,
) -> Option<String> {
    let key = format!(
        "{}&{}",
        percent_encode_unreserved(consumer_secret),
        percent_encode_unreserved(token_secret)
    );
    // One macro rather than a generic: `hmac::Hmac<D>` needs bounds that are
    // awkward to name across digest crates, and three explicit arms match how
    // the rest of this module dispatches.
    macro_rules! sign_with {
        ($alg:ty) => {{
            let mut mac = <Hmac<$alg> as KeyInit>::new_from_slice(key.as_bytes())
                .expect("HMAC accepts any key length");
            mac.update(base_string.as_bytes());
            base64::engine::general_purpose::STANDARD.encode(mac.finalize().into_bytes())
        }};
    }
    Some(match signature_method.to_ascii_uppercase().as_str() {
        "HMAC-SHA1" => sign_with!(Sha1),
        "HMAC-SHA256" => sign_with!(Sha256),
        "HMAC-SHA512" => sign_with!(Sha512),
        _ => return None,
    })
}

/// Everything [`oauth1_build_header`] needs, as plain data.
pub struct OAuth1BuildParams<'a> {
    /// HTTP method; uppercased by the builder.
    pub method: &'a str,
    /// RFC 5849 §3.4.1.2 base string URI: `scheme://host[:port]/path`, with
    /// the query and fragment stripped and the default port omitted. The
    /// caller derives this because it needs the parsed URL.
    pub base_uri: &'a str,
    /// Protocol parameters from the query string and, when the body is
    /// `application/x-www-form-urlencoded`, from the body — already
    /// percent-DECODED (§3.4.1.3.1). The `oauth_*` params are added by the
    /// builder; do not pass them here.
    pub request_params: &'a [(String, String)],
    pub consumer_key: &'a str,
    pub consumer_secret: &'a str,
    pub token: Option<&'a str>,
    pub token_secret: Option<&'a str>,
    /// One of [`OAUTH1_SIGNATURE_METHODS`], any case.
    pub signature_method: &'a str,
    pub nonce: &'a str,
    /// Seconds since the epoch, as a decimal string.
    pub timestamp: &'a str,
}

/// An OAuth1 `Authorization` header plus the base string it was signed over.
pub struct OAuth1Out {
    pub header: HeaderOut,
    /// Returned for the differential harness and for diagnosing a 401: a
    /// rejected OAuth1 request is almost always a base-string mismatch, and
    /// without this the only way to see it is a debugger.
    pub base_string: String,
}

/// Build the OAuth1 `Authorization` header (RFC 5849 §3.5.1).
///
/// Returns `None` when `signature_method` is unsupported, so the caller can
/// raise its own error naming the supported set.
pub fn oauth1_build_header(p: &OAuth1BuildParams<'_>) -> Option<OAuth1Out> {
    let method_str = p.signature_method.to_ascii_uppercase();
    if !oauth1_is_supported_signature_method(&method_str) {
        return None;
    }

    let mut oauth: Vec<(String, String)> = vec![
        ("oauth_consumer_key".to_string(), p.consumer_key.to_string()),
        ("oauth_nonce".to_string(), p.nonce.to_string()),
        ("oauth_signature_method".to_string(), method_str.clone()),
        ("oauth_timestamp".to_string(), p.timestamp.to_string()),
        ("oauth_version".to_string(), "1.0".to_string()),
    ];
    if let Some(token) = p.token {
        oauth.push(("oauth_token".to_string(), token.to_string()));
    }

    // §3.4.1.3: the base string signs the request params AND the oauth params
    // together. The header below carries only the oauth ones.
    let mut all_params: Vec<(String, String)> = p.request_params.to_vec();
    all_params.extend(oauth.clone());

    let base_string = oauth1_base_string(p.method, p.base_uri, &all_params);
    let signature = oauth1_signature(
        &base_string,
        p.consumer_secret,
        p.token_secret.unwrap_or(""),
        &method_str,
    )?;

    let mut header_params = oauth;
    header_params.push(("oauth_signature".to_string(), signature));
    header_params.sort();
    let value = header_params
        .iter()
        .map(|(k, v)| {
            format!(
                "{}=\"{}\"",
                percent_encode_unreserved(k),
                percent_encode_unreserved(v)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");

    Some(OAuth1Out {
        header: HeaderOut {
            name: "Authorization".to_string(),
            value: format!("OAuth {value}"),
        },
        base_string,
    })
}

